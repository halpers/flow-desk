"""Generate constants and distribute the authoritative event schema to service builds."""
import json
import re
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / "shared/contracts/events/v1/run.schema.json"
schema = json.loads(source.read_text(encoding="utf-8"))
definitions = schema["$defs"]


def pascal(value):
    value = re.sub(r"([a-z])([A-Z])", r"\1_\2", value)
    return "".join(part.title() for part in value.replace(".", "_").split("_"))


go = ["// Code generated by scripts/generate-runtime.py. DO NOT EDIT.", "package domain", "const ("]
py = ['"""Generated by scripts/generate-runtime.py. DO NOT EDIT."""', "", "from enum import StrEnum", ""]
ts = ["// Generated by scripts/generate-runtime.py. DO NOT EDIT."]
for key, prefix in [("runStatus", "Run"), ("eventType", "Event"), ("toolName", "Tool")]:
    values = definitions[key]["enum"]
    go.extend(prefix + pascal(value) + ' = "' + value + '"' for value in values)
    py += ["", "class " + pascal(key) + "(StrEnum):"] + ["    " + value.replace(".", "_").upper() + " = " + json.dumps(value) for value in values] + [""]
    plural = {"runStatus": "runStatuses", "eventType": "eventTypes", "toolName": "toolNames"}[key]
    ts.append("export const " + plural + " = " + json.dumps(values) + " as const;")
go.append(")")
(root / "flow-desk-serv/flowdesk/internal/domain/runtime_gen.go").write_text("\n".join(go) + "\n", encoding="utf-8")
subprocess.run(["gofmt", "-w", str(root / "flow-desk-serv/flowdesk/internal/domain/runtime_gen.go")], check=True)
(root / "flow-desk-agent/src/flowdesk_agent/runtime_gen.py").write_text("\n".join(py).rstrip() + "\n", encoding="utf-8")
(root / "flow-desk-web/src/shared/events/runtime.gen.ts").write_text("\n".join(ts) + "\n", encoding="utf-8")
for target in ["flow-desk-serv/flowdesk/internal/domain", "flow-desk-agent/src/flowdesk_agent", "flow-desk-web/src/shared/events"]:
    (root / target / "run.schema.json").write_bytes(source.read_bytes())
tool_source = root / "shared/contracts/tools/v1/read.schema.json"
for target in ["flow-desk-serv/flowdesk/internal/domain", "flow-desk-agent/src/flowdesk_agent/tools"]:
    (root / target / "read.schema.json").write_bytes(tool_source.read_bytes())
    (root / target / "actions.schema.json").write_bytes((root / "shared/contracts/tools/v1/actions.schema.json").read_bytes())
