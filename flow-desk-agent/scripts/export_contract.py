"""Export schema without opening database connections."""

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from flowdesk_agent.api.main import app  # noqa: E402
from flowdesk_agent.embeddings import EmbeddingResponse  # noqa: E402
from flowdesk_agent.reranking import Ranking  # noqa: E402

target = Path(__file__).resolve().parents[2] / "shared/contracts/agent.openapi.json"
target.write_text(
    json.dumps(app.openapi(), ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8"
)
retrieval_directory = target.parent / "retrieval/v1"
retrieval_directory.mkdir(parents=True, exist_ok=True)
for name, model in (("embedding-response", EmbeddingResponse), ("rerank-response", Ranking)):
    schema = model.model_json_schema()
    schema["$comment"] = (
        "Generated by flow-desk-agent/scripts/export_contract.py from Pydantic. DO NOT EDIT."
    )
    (retrieval_directory / (name + ".schema.json")).write_text(
        json.dumps(schema, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
